function stripAccents(s){
  return s.normalize('NFD').replace(/[\u0300-\u036f]/g,'');
}
function normalizeKey(s){
  return stripAccents(s.toLowerCase()).replace(/[^a-z]/g,'');
}
const DICT_NORM = {};
Object.keys(DICTIONARY).forEach(k=>{
  DICT_NORM[normalizeKey(k)] = { term: k, def: DICTIONARY[k] };
});

const DICT_SHORT_VERBS = new Set(['dio','vio','fue','hizo','dijo','oyo','creo','vino','tuvo','puso','salio','era']);

/** Variantes morfológicas (plurales, verbos RV1960) → posibles lemas */
function dictLookupKeys(word){
  const k = normalizeKey(word);
  if(!k) return [];
  const keys = [k];
  // Plurales: solo si el singular existe en el diccionario (evita dios→dio)
  if(k.endsWith('ces') && k.length > 4) keys.push(k.slice(0,-3)+'z');
  if(k.endsWith('es') && k.length > 5 && !k.endsWith('ies')) keys.push(k.slice(0,-2));
  if(k.endsWith('s') && k.length > 3){
    const stem = k.slice(0,-1);
    // Aceptar plural→singular solo si el singular está definido y no es pretérito corto
    if(typeof DICT_NORM !== 'undefined' && DICT_NORM[stem] && !(typeof DICT_SHORT_VERBS !== 'undefined' && DICT_SHORT_VERBS.has(stem))){
      keys.push(stem);
    } else if(!/(os|as|is|us|ios)$/.test(k) && k.length > 4){
      keys.push(stem);
    }
  }
  if(k.endsWith('itas') && k.length > 5) keys.push(k.slice(0,-1));
  // Pretéritos: exigir longitud > 5 para no tocar "dios" (4 letras)
  if(k.endsWith('o') && k.length > 5){
    const stem = k.slice(0,-1);
    keys.push(stem+'ar', stem+'er', stem+'ir');
    if(stem.endsWith('i') && stem.length > 3){
      keys.push(stem.slice(0,-1)+'er', stem.slice(0,-1)+'ar', stem.slice(0,-1)+'ir');
    }
  }
  if(k.endsWith('io') && k.length > 5){
    const stem = k.slice(0,-2);
    keys.push(stem+'er', stem+'ir', stem+'ar');
  }
  if(k.endsWith('ando') && k.length > 6) keys.push(k.slice(0,-4)+'ar');
  if(k.endsWith('iendo') && k.length > 7){ keys.push(k.slice(0,-5)+'er', k.slice(0,-5)+'ir'); }
  if(k.endsWith('ado') && k.length > 5) keys.push(k.slice(0,-3)+'ar');
  if(k.endsWith('ido') && k.length > 5) keys.push(k.slice(0,-3)+'er', k.slice(0,-3)+'ir');
  if(k.endsWith('ose') && k.length > 6) keys.push(k.slice(0,-3)+'ar', k.slice(0,-3)+'er');
  else if(k.endsWith('se') && k.length > 6) keys.push(k.slice(0,-2));
  if(k.startsWith('heaqui')) keys.push('heaqui');
  return [...new Set(keys.filter(Boolean))];
}

function lookupBiblical(word){
  const exact = normalizeKey(word);
  if(!exact) return null;
  // Coincidencia exacta siempre gana (Dios ≠ dio)
  if(DICT_NORM[exact]){
    return { term: DICT_NORM[exact].term, def: DICT_NORM[exact].def, source: 'Diccionario bíblico de SEFER' };
  }
  const keys = dictLookupKeys(word)
    .filter(k => k && k !== exact)
    .sort((a,b)=> b.length - a.length || a.localeCompare(b));
  for(const k of keys){
    if(!DICT_NORM[k]) continue;
    if((exact === k + 's' || exact === k + 'es') && DICT_SHORT_VERBS.has(k)) continue;
    return { term: DICT_NORM[k].term, def: DICT_NORM[k].def, source: 'Diccionario bíblico de SEFER' };
  }
  return null;
}
